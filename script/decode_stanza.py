# Find JSON: starts after the fd 00 08 marker + 6a token
idx = hex_str.find("6a7b")
json_hex = hex_str[idx + 2:]
json_str = codecs.decode(json_hex, "hex").decode("utf-8")

# Unescape JSON \n in base64 data (they're literal \n not actual newlines)
# The hex has literal backslash-n which becomes \n when decoded to string
parsed = json.loads(json_str)

print("=== OUR STANZA JSON ===")
print(f"queryId: {parsed['queryId']}")
inp = parsed["variables"]["input"]
print(f"input keys: {list(inp.keys())}")
print(f"nonce: {inp['nonce'][:40]}...")
print(f"reg_trace: {inp['registration_trace_id']}")
print(f"use_case: {inp['use_case']}")

ep = inp["encrypted_password"]
print(f"\nencrypted_password keys: {list(ep.keys())}")
for k in ["algorithm", "key", "nonce", "tag"]:
    print(f"  {k}: len={len(ep[k])}")

data_raw = base64.b64decode(ep["data"].replace("\n", ""))
key_raw = base64.b64decode(ep["key"].replace("\n", ""))
nonce_raw = base64.b64decode(ep["nonce"].replace("\n", ""))
tag_raw = base64.b64decode(ep["tag"].replace("\n", ""))

print(f"\ndecoded: data={len(data_raw)}B key={len(key_raw)}B nonce={len(nonce_raw)}B tag={len(tag_raw)}B")

